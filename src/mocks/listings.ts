function mockPhoto(id: string, order: number, isCover = false): ListingPhoto {
  return {
    id,
    url: `https://cdn.arsam.net.invalid/photos/${id}.webp`,
    thumbnailUrl: `https://cdn.arsam.net.invalid/photos/${id}-thumb.webp`,
    altText: `Ilan gorseli ${order + 1}`,
    order,
    isCover,
    width: 1200,
    height: 800,
    mimeType: 'image/webp',
    moderationStatus: AssetModerationStatus.Approved,
  }
}

function mockPhotos(prefix: string, count: number): ListingPhoto[] {
  return Array.from({ length: count }, (_, i) => mockPhoto(`${prefix}-${i + 1}`, i, i === 0))
}

function cleanModeration(submittedDaysAgo?: number): ModerationSummary {
  return {
    rejectionReasons: [],
    automatedChecks: [
      {
        code: AutomatedCheckCode.RequiredFields,
        status: AutomatedCheckResultStatus.Passed,
        message: 'Tum zorunlu alanlar dolu',
        checkedAt: formatMockDate(submittedDaysAgo ?? 30),
      },
      {
        code: AutomatedCheckCode.ImageQuality,
        status: AutomatedCheckResultStatus.Passed,
        message: 'Gorsel kalitesi yeterli',
        checkedAt: formatMockDate(submittedDaysAgo ?? 30),
      },
    ],
    ...(submittedDaysAgo !== undefined && { submittedAt: formatMockDate(submittedDaysAgo) }),
  }
}

function pendingModeration(submittedDaysAgo: number, reviewerId?: string): ModerationSummary {
  return {
    ...(reviewerId !== undefined && { currentReviewerId: reviewerId }),
    submittedAt: formatMockDate(submittedDaysAgo),
    rejectionReasons: [],
    automatedChecks: [
      {
        code: AutomatedCheckCode.RequiredFields,
        status: AutomatedCheckResultStatus.Passed,
        message: 'Tum zorunlu alanlar dolu',
        checkedAt: formatMockDate(submittedDaysAgo),
      },
      {
        code: AutomatedCheckCode.DuplicateContent,
        status: AutomatedCheckResultStatus.Passed,
        message: 'Benzer ilan bulunamadi',
        checkedAt: formatMockDate(submittedDaysAgo),
      },
      {
        code: AutomatedCheckCode.PriceAnomaly,
        status: AutomatedCheckResultStatus.Passed,
        message: 'Fiyat bolge ortalamasina uygun',
        checkedAt: formatMockDate(submittedDaysAgo),
      },
    ],
  }
}

function seller(userId: string, name: string, type: SellerType, verified: boolean, companyName?: string): SellerSummary {
  return {
    id: userId,
    type,
    displayName: name,
    ...(companyName !== undefined && { companyName }),
    verificationStatus: verified ? SellerVerificationStatus.Verified : SellerVerificationStatus.Unverified,
  }
}

function tryPrice(amount: number, period: PricePeriod = PricePeriod.OneTime, negotiable = true): Money {
  return { amount, currency: Currency.Try, period, negotiable }
}

